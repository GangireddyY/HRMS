-- Row-level security on every organization-owned table, behind the ORM tenant hooks. The API sets
-- app.organization_id on each connection before a statement: the request's organization, or '' when the statement
-- opted out of tenant scoping (identity, platform administration, jobs). Rows of other organizations are then neither
-- visible nor writable, including through raw SQL and nested includes. FORCE applies the policies to the table owner
-- too; only superusers and BYPASSRLS roles are exempt.

CREATE OR REPLACE FUNCTION "hrms_tenant_visible"("org" UUID) RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN coalesce(current_setting('app.organization_id', true), '') = '' THEN true
              ELSE "org" IS NOT DISTINCT FROM current_setting('app.organization_id', true)::uuid END
$$;

