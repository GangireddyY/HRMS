/** Printable HTML for statutory documents (the browser prints them to PDF). */

const esc = (v: unknown) => String(v ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
const inr = (n: number) => n.toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const fyLabel = (fy: number) => `${fy}-${String((fy + 1) % 100).padStart(2, '0')}`;

function page(title: string, body: string): string {
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${esc(title)}</title><style>
body{font-family:"Segoe UI",Arial,sans-serif;color:#111827;margin:32px;font-size:13px}
h1{font-size:18px;margin:0 0 4px}h2{font-size:14px;margin:24px 0 8px;border-bottom:1px solid #d1d5db;padding-bottom:4px}
p.muted{color:#6b7280;margin:0}table{border-collapse:collapse;width:100%;margin-top:6px}
th,td{border:1px solid #d1d5db;padding:6px 8px;text-align:left;vertical-align:top}th{background:#f3f4f6;font-weight:600}
td.n{text-align:right;font-variant-numeric:tabular-nums}.grid{display:grid;grid-template-columns:1fr 1fr;gap:12px}
.box{border:1px solid #d1d5db;padding:10px;border-radius:6px}.sign{margin-top:48px;display:flex;justify-content:space-between}
@media print{body{margin:12mm}button{display:none}}
</style></head><body>${body}<p class="muted" style="margin-top:32px">Generated by HRMS on ${new Date().toISOString().slice(0, 10)}.</p></body></html>`;
}

export interface Form16Data {
  financialYear: number;
  employer: { name: string; tan: string | null; address: string | null };
  employee: { name: string; employeeCode: string; pan: string | null; designation: string | null; periodFrom: string; periodTo: string };
  regime: 'OLD' | 'NEW';
  grossSalary: number;
  previousEmployerIncome: number;
  hraExemption: number;
  standardDeduction: number;
  professionalTax: number;
  deductions: { section80c: number; section80ccd1b: number; section80d: number; homeLoanInterest: number };
  taxableIncome: number;
  slabTax: number;
  rebate: number;
  surcharge: number;
  cess: number;
  totalTax: number;
  tdsDeducted: number;
  previousEmployerTds: number;
  quarters: { quarter: string; amountPaid: number; tds: number }[];
}

/** Form 16 Part B (annexure): salary paid, exemptions, deductions and tax deducted for the financial year. */
export function form16Html(d: Form16Data): string {
  const row = (label: string, amount: number) => `<tr><td>${esc(label)}</td><td class="n">${inr(amount)}</td></tr>`;
  const body = `<h1>Form No. 16 – Part B</h1>
<p class="muted">Certificate under section 203 of the Income-tax Act, 1961 for tax deducted at source on salary · Financial year ${fyLabel(d.financialYear)} (assessment year ${fyLabel(d.financialYear + 1)})</p>
<div class="grid" style="margin-top:16px">
<div class="box"><strong>Employer (deductor)</strong><br>${esc(d.employer.name)}<br>TAN: ${esc(d.employer.tan ?? 'not set')}${d.employer.address ? `<br>${esc(d.employer.address)}` : ''}</div>
<div class="box"><strong>Employee (deductee)</strong><br>${esc(d.employee.name)} (${esc(d.employee.employeeCode)})<br>PAN: ${esc(d.employee.pan ?? 'not furnished')}${d.employee.designation ? `<br>${esc(d.employee.designation)}` : ''}<br>Period: ${esc(d.employee.periodFrom)} to ${esc(d.employee.periodTo)}</div>
</div>
<h2>Summary of tax deducted at source (Part A summary)</h2>
<table><tr><th>Quarter</th><th>Amount paid / credited</th><th>Tax deducted</th></tr>
${d.quarters.map((q) => `<tr><td>${esc(q.quarter)}</td><td class="n">${inr(q.amountPaid)}</td><td class="n">${inr(q.tds)}</td></tr>`).join('')}
<tr><th>Total</th><th class="n">${inr(d.quarters.reduce((n, q) => n + q.amountPaid, 0))}</th><th class="n">${inr(d.tdsDeducted)}</th></tr></table>
<h2>Details of salary paid and tax deducted (${d.regime === 'NEW' ? 'new regime, section 115BAC' : 'old regime'})</h2>
<table><tr><th>Particulars</th><th>Amount (₹)</th></tr>
${row('1. Gross salary from this employer', d.grossSalary)}
${d.previousEmployerIncome ? row('   Salary from previous employer(s) this year', d.previousEmployerIncome) : ''}
${row('2. Less: allowance exempt under section 10 (house rent allowance)', d.hraExemption)}
${row('3. Less: standard deduction under section 16(ia)', d.standardDeduction)}
${row('   Less: tax on employment under section 16(iii)', d.professionalTax)}
${row('4. Less: deductions under Chapter VI-A – section 80C', d.deductions.section80c)}
${row('   section 80CCD(1B)', d.deductions.section80ccd1b)}
${row('   section 80D', d.deductions.section80d)}
${row('   Interest on housing loan, section 24(b)', d.deductions.homeLoanInterest)}
${row('5. Total taxable income (rounded under section 288A)', d.taxableIncome)}
${row('6. Tax on total income', d.slabTax)}
${row('7. Less: rebate under section 87A', d.rebate)}
${row('8. Surcharge', d.surcharge)}
${row('9. Health and education cess', d.cess)}
${row('10. Tax payable', d.totalTax)}
${d.previousEmployerTds ? row('11. Tax deducted by previous employer(s)', d.previousEmployerTds) : ''}
${row('12. Tax deducted by this employer', d.tdsDeducted)}
${row(d.totalTax - d.tdsDeducted - d.previousEmployerTds >= 0 ? '13. Tax still payable' : '13. Tax deducted in excess (refundable)', Math.abs(d.totalTax - d.tdsDeducted - d.previousEmployerTds))}
</table>
<p class="muted" style="margin-top:8px">Part A (with challan and BIN details) is downloaded from the TRACES portal. This annexure is worked out from the approved payroll for the year.</p>
<div class="sign"><div>Place: ____________<br>Date: ____________</div><div>Signature of the person responsible for deduction of tax<br>Name: ______________________ Designation: ____________</div></div>`;
  return page(`Form 16 ${fyLabel(d.financialYear)} – ${d.employee.name}`, body);
}

export interface Form12bbData {
  financialYear: number;
  employee: { name: string; employeeCode: string; pan: string | null; address: string | null };
  employer: { name: string };
  regime: 'OLD' | 'NEW';
  rentPaidAnnual: number;
  metroCity: boolean;
  homeLoanInterest: number;
  section80c: number;
  section80ccd1b: number;
  section80d: number;
  proofs: { section: string; description: string; amount: number; status: string; acceptedAmount: number | null }[];
}

/** Form 12BB: the employee's statement of claims for deduction of tax, with the evidence submitted. */
export function form12bbHtml(d: Form12bbData): string {
  const evidence = (section: string) =>
    d.proofs
      .filter((p) => p.section === section)
      .map((p) => {
        const status =
          p.status === 'ACCEPTED'
            ? p.acceptedAmount !== null && p.acceptedAmount !== p.amount
              ? `₹${inr(p.acceptedAmount)} accepted`
              : 'accepted'
            : p.status === 'REJECTED'
              ? 'not accepted'
              : 'awaiting review';
        return `${esc(p.description)} (₹${inr(p.amount)}, ${status})`;
      })
      .join('<br>') || '—';
  const body = `<h1>Form No. 12BB</h1>
<p class="muted">Statement showing particulars of claims by an employee for deduction of tax (see rule 26C) · Financial year ${fyLabel(d.financialYear)}</p>
<table style="margin-top:16px">
<tr><th style="width:35%">Name and address of the employee</th><td>${esc(d.employee.name)} (${esc(d.employee.employeeCode)})${d.employee.address ? `<br>${esc(d.employee.address)}` : ''}</td></tr>
<tr><th>Permanent account number (PAN)</th><td>${esc(d.employee.pan ?? 'not furnished')}</td></tr>
<tr><th>Employer</th><td>${esc(d.employer.name)}</td></tr>
<tr><th>Tax regime chosen</th><td>${d.regime === 'NEW' ? 'New regime (section 115BAC): these deductions are not available' : 'Old regime'}</td></tr>
</table>
<h2>Details of claims and evidence</h2>
<table><tr><th>Nature of claim</th><th>Amount (₹)</th><th>Evidence / particulars</th></tr>
<tr><td>1. House rent allowance – rent paid to the landlord${d.metroCity ? ' (metro city)' : ''}</td><td class="n">${inr(d.rentPaidAnnual)}</td><td>${evidence('HRA')}<br>Name, address and PAN of the landlord (if rent is above ₹1,00,000 a year): ______________________</td></tr>
<tr><td>2. Leave travel concession or assistance</td><td class="n">—</td><td>—</td></tr>
<tr><td>3. Deduction of interest on borrowing (section 24)</td><td class="n">${inr(d.homeLoanInterest)}</td><td>${evidence('HOME_LOAN')}<br>Name, address and PAN of the lender: ______________________</td></tr>
<tr><td>4. Chapter VI-A – section 80C, 80CCC and 80CCD(1)</td><td class="n">${inr(d.section80c)}</td><td>${evidence('80C')}</td></tr>
<tr><td>   section 80CCD(1B)</td><td class="n">${inr(d.section80ccd1b)}</td><td>${evidence('80CCD1B')}</td></tr>
<tr><td>   section 80D</td><td class="n">${inr(d.section80d)}</td><td>${evidence('80D')}</td></tr>
</table>
<h2>Verification</h2>
<p>I, ${esc(d.employee.name)}, do hereby certify that the information given above is complete and correct.</p>
<div class="sign"><div>Place: ____________<br>Date: ____________</div><div>Signature of the employee<br>Designation: ____________</div></div>`;
  return page(`Form 12BB ${fyLabel(d.financialYear)} – ${d.employee.name}`, body);
}
