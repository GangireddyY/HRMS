import { DeleteObjectCommand, GetObjectCommand, NoSuchKey, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { Injectable, Logger } from '@nestjs/common';
import { createReadStream } from 'node:fs';
import { mkdir, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, resolve, sep } from 'node:path';
import { Readable } from 'node:stream';
import { AppError } from '../../common/errors/app-error';
import type { AuditService } from '../audit/audit.service';
import { TestSignatureScanner, type MalwareScanner, type ScanVerdict } from './malware-scanner';

/** Object keys are generated by the API (never from user input): lowercase letters, digits, `-`, `_`, `.` and `/`. */
const KEY_PATTERN = /^[a-z0-9][a-z0-9/_.-]{0,499}$/;

export interface StorageDriver {
  put(key: string, data: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Readable>;
  delete(key: string): Promise<void>;
}

/** Local disk; for development and tests only (rejected in production by env validation). */
export class LocalStorageDriver implements StorageDriver {
  private readonly root: string;

  constructor(dir: string) {
    this.root = isAbsolute(dir) ? dir : resolve(process.cwd(), dir);
  }

  private path(key: string): string {
    const full = resolve(this.root, key);
    if (!full.startsWith(this.root + sep)) throw new Error('Storage key escapes the storage root');
    return full;
  }

  async put(key: string, data: Buffer): Promise<void> {
    const file = this.path(key);
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, data, { flag: 'wx' });
  }

  async get(key: string): Promise<Readable> {
    const file = this.path(key);
    try {
      await stat(file);
    } catch {
      throw AppError.notFound('File');
    }
    return createReadStream(file);
  }

  async delete(key: string): Promise<void> {
    await rm(this.path(key), { force: true });
  }
}

/** Amazon S3 or an S3-compatible store; objects are encrypted at rest (SSE-S3) and never public. */
export class S3StorageDriver implements StorageDriver {
  private readonly client: S3Client;

  constructor(
    private readonly bucket: string,
    options: { region: string; endpoint?: string; forcePathStyle?: boolean },
  ) {
    this.client = new S3Client({ region: options.region, endpoint: options.endpoint || undefined, forcePathStyle: options.forcePathStyle });
  }

  async put(key: string, data: Buffer, contentType: string): Promise<void> {
    await this.client.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: data, ContentType: contentType, ServerSideEncryption: 'AES256' }));
  }

  async get(key: string): Promise<Readable> {
    try {
      const res = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
      return res.Body as Readable;
    } catch (e) {
      if (e instanceof NoSuchKey) throw AppError.notFound('File');
      throw e;
    }
  }

  async delete(key: string): Promise<void> {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

/**
 * Private file storage. Files are only ever served through authorized API endpoints.
 * Uploads are scanned for malware before they are stored, failing closed: an infected file is rejected (and audited),
 * and when the scanner can't answer nothing is stored. Only content the API generates itself skips the scan.
 */
@Injectable()
export class StorageService {
  private readonly logger = new Logger(StorageService.name);

  constructor(
    private readonly driver: StorageDriver,
    private readonly scanner: MalwareScanner = new TestSignatureScanner(),
    private readonly audit?: AuditService,
  ) {}

  /** Whether the malware scanner answers (null when it has no way to tell). */
  async scannerUp(): Promise<{ name: string; up: boolean | null }> {
    return { name: this.scanner.name, up: this.scanner.ping ? await this.scanner.ping() : null };
  }

  async put(key: string, data: Buffer, contentType: string, opts: { generated?: boolean } = {}): Promise<void> {
    this.assertKey(key);
    if (!opts.generated) await this.scan(key, data, contentType);
    return this.driver.put(key, data, contentType);
  }

  private async scan(key: string, data: Buffer, contentType: string): Promise<void> {
    let verdict: ScanVerdict;
    try {
      verdict = await this.scanner.scan(data);
    } catch (e) {
      this.logger.error(`Malware scan unavailable (${this.scanner.name}): ${(e as Error).message}`);
      throw new AppError('SCAN_UNAVAILABLE', "Files can't be checked for viruses right now, so nothing was uploaded. Try again in a few minutes.");
    }
    if (verdict.clean) return;
    // The area of the app (e.g. "employees", "grievances") without the organization or record ids.
    const area = key.split('/')[2] ?? key.split('/')[0];
    this.logger.warn(`Upload blocked: ${verdict.signature} (${area}, ${contentType}, ${data.length} bytes)`);
    await this.audit?.record({ action: 'security.upload_blocked', entityType: 'Upload', summary: `An uploaded file was blocked: ${verdict.signature}`, metadata: { area, contentType, size: data.length, scanner: this.scanner.name } });
    throw new AppError('FILE_REJECTED', 'This file was blocked because it contains malware. If you think this is a mistake, contact your administrator.');
  }

  get(key: string): Promise<Readable> {
    this.assertKey(key);
    return this.driver.get(key);
  }

  delete(key: string): Promise<void> {
    this.assertKey(key);
    return this.driver.delete(key);
  }

  /** Deletes after the database change committed; a failure leaves an orphaned object, which is logged rather than undoing the change. */
  async deleteQuietly(keys: string[]): Promise<void> {
    for (const key of keys) {
      try {
        await this.delete(key);
      } catch (e) {
        this.logger.error(`Could not delete stored object ${key}: ${(e as Error).message}`);
      }
    }
  }

  private assertKey(key: string): void {
    if (!KEY_PATTERN.test(key) || key.includes('..') || key.includes('//')) throw new Error(`Invalid storage key: ${key}`);
  }
}
